    expect(source).toContain("const PULLBACK_REFERENCE_RING_RADIUS = 530");
    expect(source).toContain("const PULLBACK_REFERENCE_SCALE = OUTER_PARTICLE_RADIUS / PULLBACK_REFERENCE_RING_RADIUS");
    expect(source).toContain("const PULLBACK_REFERENCE_RADIUS = Math.hypot(30, 600) * PULLBACK_REFERENCE_SCALE");
