    expect(source).toContain("const fireflyCount = 6500");
    expect(source).toContain("const middleCount = 60000");
    expect(source).toContain("renderer.setPixelRatio(Math.min(window.devicePixelRatio, 1.2))");
    expect(source).toContain("const AURORA_POINT_COUNT = 34");
