    expect(source).toContain("const outerColor = (brightness: number, saturation = OUTER_COLOR_SATURATION)");
    expect(source).toContain("const color = outerColor(OUTER_COLOR_MIN_BRIGHTNESS + random() * OUTER_COLOR_VARIATION, distanceSaturation)");
    expect(source).toContain("const FORMER_MIDDLE_PARTICLE_SIZE = 0.44");
